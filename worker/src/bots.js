/**
 * src/bots.js — Bot lifecycle (create / list / revoke) + grant issuing.
 *
 * Routes:
 *   POST /api/bots                  create a bot, returns grant JWT
 *   GET  /api/bots                  list the caller's bots
 *   POST /api/bots/:id/revoke       revoke a bot
 *
 * Bots are the unit of trust for the recall API. Each bot gets:
 *   * an Ed25519 public key, stored on the bots row (private key never
 *     leaves the bot — the *server* never sees it; this is enforced by
 *     the API not accepting it on create).
 *   * a scope_tags list — labels the bot is allowed to read (e.g.
 *     `["decisions", "rust-projects"]`).
 *   * an optional expires_at — beyond which the JWT is invalid even if
 *     it hasn't been revoked.
 *
 * On create we mint a short-lived (default 15min) grant JWT scoped to
 * the bot's manifest. Subsequent calls to /mem/v1/recall and
 * /mem/v1/full-recall present this grant.
 *
 * IMPORTANT: the bot's Ed25519 private key is *generated by the worker*
 * and returned to the caller exactly once. The caller is responsible for
 * storing it; if they lose it they must revoke + re-create. We never
 * store the private key server-side.
 */

import {
  createBot,
  getBot,
  listBots,
  revokeBot,
} from './db.js';
import { signGrant, verifyGrant, SCOPE_WRITE } from './auth.js';

// ---------------------------------------------------------------------------
// Ed25519 keypair generation via WebCrypto.
//
// Cloudflare Workers exposes `crypto.subtle.generateKey` with Ed25519 in
// the Web Crypto API surface. We use it directly — no third-party dep.
// ---------------------------------------------------------------------------

/**
 * Generate a fresh Ed25519 keypair and return both halves in a
 * transport-friendly format (raw bytes for the public key, PKCS8-ish
 * raw bytes for the private — Workers exposes Ed25519 privateKey in
 * PKCS8 form via subtle.exportKey).
 *
 * Returns: { public_raw: Uint8Array, private_pkcs8: Uint8Array }
 */
async function generateEd25519() {
  const kp = await crypto.subtle.generateKey(
    { name: 'Ed25519' },
    true,
    ['sign', 'verify'],
  );
  const rawPub = new Uint8Array(await crypto.subtle.exportKey('raw', kp.publicKey));
  const rawPriv = new Uint8Array(await crypto.subtle.exportKey('pkcs8', kp.privateKey));
  return { public_raw: rawPub, private_pkcs8: rawPriv };
}

function b64(bytes) {
  let s = '';
  for (let i = 0; i < bytes.length; i++) s += String.fromCharCode(bytes[i]);
  return btoa(s);
}

function bytesEq(a, b) {
  if (!a || !b || a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
  return true;
}

/**
 * Decode a base64 string to bytes. Returns null on garbage input rather
 * than throwing.
 *
 * @param {string} s
 */
function decodeMaybe(s) {
  if (typeof s !== 'string' || !s) return null;
  try {
    const bin = atob(s);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  } catch (_) {
    return null;
  }
}

function uuid() {
  // crypto.randomUUID is available in Workers.
  return crypto.randomUUID();
}

