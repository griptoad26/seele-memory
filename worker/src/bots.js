/**
 * POST /api/bots
 *
 * Headers: Authorization: Bearer <device_token>
 *
 * Body:
 *   {
 *     name: string,
 *     scope_tags?: string[],
 *     ttl_seconds?: number,   // grant TTL, default 900 (15 min)
 *   }
 *
 * Response 200:
 *   {
 *     bot_id:          string,
 *     user_id:         string,
 *     name:            string,
 *     scope_tags:      string[],
 *     grant:           { jwt, expires_at, scope },
 *     private_key:     string,    // base64 PKCS8 — RETURNED ONCE
 *     public_key:      string,    // base64 raw
 *     warning:         'store the private_key now; it will not be shown again',
 *   }
 *
 * Response 401: auth failure
 * Response 500: server / db / crypto failure
 */
export async function handleCreateBot(request, env, requestUserId) {
  // requestUserId is supplied by the auth wrapper (the verified JWT's sub).
  // We re-verify inside the handler so the dependency is explicit — this
  // also catches cases where the route was wired up without auth.
  const auth = await verifyGrant({
    secret: env.GRANT_JWT,
    authorization: request.headers.get('Authorization'),
    required_scope: SCOPE_WRITE,
    db: env.DB,
  });
  if (!auth.ok) {
    return { status: auth.error.status, body: { error: auth.error.code, message: auth.error.message } };
  }
  const user_id = auth.claims.sub;
  if (requestUserId && requestUserId !== user_id) {
    return { status: 403, body: { error: 'user_mismatch', message: 'auth sub does not match' } };
  }

  const body = await safeJson(request);
  if (!body || typeof body !== 'object') {
    return { status: 400, body: { error: 'bad_request', message: 'JSON body required' } };
  }
  if (typeof body.name !== 'string' || !body.name) {
    return { status: 400, body: { error: 'bad_request', message: '`name` is required' } };
  }
  const scope_tags = Array.isArray(body.scope_tags)
    ? body.scope_tags.filter((t) => typeof t === 'string')
    : [];
  const ttl_seconds = Number.isFinite(body.ttl_seconds) && body.ttl_seconds > 0
    ? Math.min(body.ttl_seconds, 24 * 60 * 60) // cap at 1 day for safety
    : 900;

  let keypair;
  try {
    keypair = await generateEd25519();
  } catch (err) {
    return { status: 500, body: { error: 'crypto_error', message: String((err && err.message) || err) } };
  }

  const bot_id = uuid();
  try {
    await createBot(env.DB, {
      bot_id,
      user_id,
      name: body.name,
      public_key_ed25519: keypair.public_raw,
      scope_tags,
      expires_at: null,
    });
  } catch (err) {
    return { status: 500, body: { error: 'db_error', message: String((err && err.message) || err) } };
  }

  let grant;
  try {
    grant = await signGrant({
      secret: env.GRANT_JWT,
      sub: user_id,
      bot_id,
      scope: SCOPE_WRITE, // write grants include recall by transitivity
      ttl_seconds,
      issuer: 'seele-cloud:bot',
    });
  } catch (err) {
    return { status: 500, body: { error: 'sign_error', message: String((err && err.message) || err) } };
  }

  return {
    status: 200,
    body: {
      bot_id,
      user_id,
      name: body.name,
      scope_tags,
      grant: {
        jwt: grant.jwt,
        expires_at: grant.expires_at,
        scope: SCOPE_WRITE,
      },
      private_key: b64(keypair.private_pkcs8),
      public_key: b64(keypair.public_raw),
      warning: 'store the private_key now; it will not be shown again',
    },
  };
}

/**
 * GET /api/bots
 *
 * Headers: Authorization: Bearer <device_token>
 *
 * Response 200: { bots: [{ bot_id, name, scope_tags, created_at, revoked_at }] }
 */
export async function handleListBots(request, env) {
  const auth = await verifyGrant({
    secret: env.GRANT_JWT,
    authorization: request.headers.get('Authorization'),
    required_scope: SCOPE_WRITE,
    db: env.DB,
  });
  if (!auth.ok) {
    return { status: auth.error.status, body: { error: auth.error.code, message: auth.error.message } };
  }

  let rows;
  try {
    rows = await listBots(env.DB, auth.claims.sub);
  } catch (err) {
    return { status: 500, body: { error: 'db_error', message: String((err && err.message) || err) } };
  }
  return {
    status: 200,
    body: {
      bots: rows.map((r) => ({
        bot_id: r.bot_id,
        name: r.name,
        scope_tags: safeParseArray(r.scope_tags),
        created_at: r.created_at,
        revoked_at: r.revoked_at,
      })),
    },
  };
}

/**
 * POST /api/bots/:id/revoke
 *
 * Headers: Authorization: Bearer <device_token>
 *
 * Response 200: { bot_id, revoked_at }
 * Response 404: { error: 'not_found' }
 * Response 403: { error: 'not_your_bot' } — bot belongs to a different user
 */
export async function handleRevokeBot(request, env, bot_id) {
  const auth = await verifyGrant({
    secret: env.GRANT_JWT,
    authorization: request.headers.get('Authorization'),
    required_scope: SCOPE_WRITE,
    db: env.DB,
  });
  if (!auth.ok) {
    return { status: auth.error.status, body: { error: auth.error.code, message: auth.error.message } };
  }
  if (!bot_id) {
    return { status: 400, body: { error: 'bad_request', message: 'bot_id path param required' } };
  }
  // Confirm ownership before attempting revocation so we can return a
  // distinct 403 vs a benign 404.
  const existing = await getBot(env.DB, bot_id);
  if (!existing) {
    return { status: 404, body: { error: 'not_found' } };
  }
  if (existing.user_id !== auth.claims.sub) {
    return { status: 403, body: { error: 'not_your_bot' } };
  }
  const res = await revokeBot(env.DB, bot_id, auth.claims.sub);
  const meta = res.meta || {};
  const changes = Number.isFinite(meta.changes) ? meta.changes : (res.changes || 0);
  if (changes === 0) {
    // Already revoked — return success with the prior timestamp.
    return {
      status: 200,
      body: { bot_id, revoked_at: existing.revoked_at, already_revoked: true },
    };
  }
  return {
    status: 200,
    body: { bot_id, revoked_at: Date.now() },
  };
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

async function safeJson(request) {
  try {
    return await request.json();
  } catch (_) {
    return null;
  }
}

function safeParseArray(s) {
  try {
    const v = JSON.parse(s);
    return Array.isArray(v) ? v : [];
  } catch (_) {
    return [];
  }
}

// Re-export so tests can poke at internals without reaching past auth.
export { generateEd25519, decodeMaybe, uuid, b64, bytesEq };